#!/usr/bin/env python3
"""gen_kit.py <tree> <kit-dir> - the Ant tree's part of the PCSI kit.

<tree> is the staged distribution (staging/apache-ant-<version>); the kit
installs it as [ANT] (ANT$ROOT:[000000], the Ant home), with the images
BUILD.COM makes in its [.BIN].  Adapted from vms-maven's.  Writes:

  <kit-dir>/tree.pdf          directory and file lines for the product
                              description; each file gets a flat material name
                              (Rnnnnn.DAT), because PCSI looks material up by
                              name in one directory and the tree has several
                              file of one name (vms-maven NOTES N26)
  <kit-dir>/KIT_MATERIAL.COM  run by MAKE_KIT.COM in the tree: copies each file
                              to its material name in P1
  <kit-dir>/ANT$CASE.COM      run by ANT$STARTUP.COM INSTALL: PCSI stores names
                              in upper case; this renames each file back to its
                              real name (the jars, the manual's pages)

Left out: the Unix and Windows scripts in bin/, which cannot run on OpenVMS
(ANT.EXE does what bin/ant does), and [.VMSPORT].
"""
import os
import sys

# Built on the node by BUILD.COM, not in the staged tree.
BUILT = [(['bin'], 'ANT.EXE'), (['bin'], 'ANTDCL.EXE')]
LEFT_OUT = {'bin/' + f for f in (
    'ant', 'ant.bat', 'ant.cmd', 'antRun', 'antRun.bat', 'antRun.pl', 'antenv.cmd',
    'complete-ant-cmd.pl', 'envset.cmd', 'lcp.bat', 'runant.pl', 'runant.py', 'runrc.cmd')}
LEFT_OUT_DIRS = {'vmsport'}

# Characters an ODS-5 name escapes with "^" (besides interior dots); PCSI's
# product description takes none of them (vms-vim NOTES N19).
SPECIAL = set(' !#&\'()+,;=@[]^`{}~%')


def vms_name(name):
    """A file name as an ODS-5 VMS spec: interior dots escaped, a type always."""
    if any(c in SPECIAL for c in name):
        sys.exit('gen_kit: PCSI cannot name %s' % name)
    head, dot, ext = name.rpartition('.')
    if not dot:
        return name + '.'
    return head.replace('.', '^.') + '.' + ext


def vms_dir(parts):
    for p in parts:
        if '.' in p or any(c in SPECIAL for c in p):
            sys.exit('gen_kit: directory name needs escaping, not handled: %s' % p)
    return ''.join('.' + p for p in parts)


def main():
    tree, kit = sys.argv[1], sys.argv[2]
    dirs, files = [], []
    for top, dnames, fnames in os.walk(tree):
        rel = os.path.relpath(top, tree)
        parts = [] if rel == '.' else rel.split(os.sep)
        dnames[:] = sorted(d for d in dnames if '/'.join(parts + [d]) not in LEFT_OUT_DIRS)
        if parts:
            dirs.append(parts)
        for f in sorted(fnames):
            if '/'.join(parts + [f]) not in LEFT_OUT:
                files.append((parts, f))
    files += BUILT

    with open(os.path.join(kit, 'tree.pdf'), 'w') as pdf:
        for parts in dirs:
            pdf.write('    directory [ANT%s] ;\n' % vms_dir(parts).upper())
        for i, (parts, f) in enumerate(files, 1):
            pdf.write('    file [ANT%s]%s source [000000]R%05d.DAT ;\n'
                      % (vms_dir(parts).upper(), vms_name(f).upper(), i))

    with open(os.path.join(kit, 'KIT_MATERIAL.COM'), 'w') as m:
        m.write('$! KIT_MATERIAL.COM <material-dir> - generated by tools/gen_kit.py.\n'
                '$! Run by MAKE_KIT.COM with the Ant tree as the default directory:\n'
                '$! copies each file the kit installs to its material name.\n'
                '$ set noon\n'
                '$ bad = 0\n')
        for i, (parts, f) in enumerate(files, 1):
            m.write('$ copy/nolog [%s]%s %sR%05d.DAT\n'
                    '$ if .not. $status then bad = bad + 1\n'
                    % (vms_dir(parts), vms_name(f), "'p1'", i))
        m.write('$ if bad .gt. 0 then write sys$error "KIT_MATERIAL: ' "''bad'" ' files not copied"\n'
                '$ if bad .gt. 0 then exit 44\n'
                '$ write sys$output "MAKE_KIT: copied %d files"\n'
                '$ exit 1\n' % len(files))

    with open(os.path.join(kit, 'ANT$CASE.COM'), 'w') as c:
        c.write('$! ANT$CASE.COM - generated by tools/gen_kit.py; run by\n'
                '$! ANT$STARTUP.COM INSTALL.  PCSI installs every file with an upper-case\n'
                '$! name; give each file its real name again, as in the distribution\n'
                '$! (on ODS-5, RENAME can change just the case).\n'
                '$ set noon\n'
                '$ saved_parse = f$getjpi("", "PARSE_STYLE_PERM")\n'
                '$ set process/parse_style=extended\n'
                '$ bad = 0\n')
        n = 0
        for parts, f in files:
            v = vms_name(f)
            if v == v.upper():
                continue
            d = 'ANT$ROOT:[%s]' % (vms_dir(parts)[1:].upper() or '000000')
            c.write('$ rename/nolog %s%s; %s%s\n'
                    '$ if .not. $status then bad = bad + 1\n' % (d, v.upper(), d, v))
            n += 1
        c.write('$ set process/parse_style=\'saved_parse\'\n'
                '$ if bad .gt. 0 then write sys$error "ANT$CASE: ' "''bad'" ' of %d files kept upper-case names"\n'
                '$ exit 1\n' % n)
    print('gen_kit: %d directories, %d files (%d renamed at install)'
          % (len(dirs) + 1, len(files), n))


if __name__ == '__main__':
    main()
